export const CUSTOM_METRICS_CODE_EXAMPLE = `import http from 'k6/http';
import { check, sleep } from 'k6';
import { Counter, Gauge, Rate, Trend } from 'k6/metrics';

// 1. Counter: Tracks cumulative counts (always increases)
const ordersSubmittedCount = new Counter('orders_submitted_total');

// 2. Gauge: Tracks the current instantaneous value (can go up or down)
const cartItemCountGauge = new Gauge('current_cart_items_gauge');

// 3. Rate: Tracks the proportion of events matching a condition (0 to 1)
const paymentSuccessRate = new Rate('payment_success_rate');

// 4. Trend: Calculates min, max, avg, med, p(90), p(95), p(99) on custom timings
const paymentGatewayLatency = new Trend('payment_gateway_latency_ms');

export const options = {
  vus: 10,
  duration: '30s',
  thresholds: {
    'orders_submitted_total': ['count>50'],
    'payment_success_rate': ['rate>0.98'], // 98% payment success
    'payment_gateway_latency_ms': ['p(95)<450'], // 95% payments under 450ms
  },
};

export default function () {
  const orderPayload = JSON.stringify({
    customer: 'rahul.verma@enterprise-retail.com',
    items: [{ sku: 'KEYCHRON-K2-V2', price: 89.99, qty: 1 }],
  });

  // Track instantaneous cart item size
  cartItemCountGauge.add(1);

  const startTime = Date.now();
  const res = http.post('https://orders-api.company.internal/api/v1/orders', orderPayload, {
    headers: { 'Content-Type': 'application/json' },
  });
  const latency = Date.now() - startTime;

  const passed = check(res, {
    'order processed': (r) => r.status === 201,
  });

  if (passed) {
    ordersSubmittedCount.add(1);
    paymentSuccessRate.add(1); // 1 = Success
    paymentGatewayLatency.add(latency);
  } else {
    paymentSuccessRate.add(0); // 0 = Failure
  }

  sleep(1);
}`;

